function normalized(value) {
  return String(value ?? '')
    .toLowerCase()
    .replace(/s[.\s]*m[.\s]*a[.\s]*r[.\s]*t[.]?/g, 'smart')
    .replace(/[’']/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
function root(token) {
  if (token.length > 6 && token.endsWith('ing')) return token.slice(0,-3);
  if (token.length > 5 && token.endsWith('ed')) return token.slice(0,-2);
  if (token.length > 5 && token.endsWith('es')) return token.slice(0,-2);
  if (token.length > 4 && token.endsWith('s')) return token.slice(0,-1);
  return token;
}
function tokens(value) {
  return [...new Set(normalized(value).split(' ').map(root).filter((token)=>token.length>=3&&!STOP_WORDS.has(token)))];
}
function lessonSearchText(lesson) {
  const objectives=Array.isArray(lesson?.learning_objectives)?lesson.learning_objectives:Array.isArray(lesson?.objectives)?lesson.objectives:[];
  const skills=Array.isArray(lesson?.skill_focus)?lesson.skill_focus:[];
  let text=[lesson?.title,lesson?.unit,...skills,...objectives.map((item)=>typeof item==='string'?item:item?.text)].filter(Boolean).join(' ');
  const lower=text.toLowerCase();
  for(const [phrase,extra] of Object.entries(EXPANSIONS)) if(lower.includes(phrase)) text+=' '+extra;
  return text;
}
function targetCode(value) {
  return String(value??'').match(/\b([678]\.[1-5](?:\.[a-z])?)\b/i)?.[1]?.toLowerCase()??null;
}
function score(entry, query) {
  const text=normalized(entry.text);
  return tokens(query).reduce((total,token)=>total+(text.includes(token)?(token.length>=8?3:token.length>=5?2:1):0),0);
}
function best(entries, query) {
  let chosen=null, high=0;
  for(const entry of entries.filter((item)=>!item.isParent)){
    const value=score(entry,query);
    if(value>high){chosen=entry;high=value;}
  }
  return high>=2?chosen:null;
}
function peStrand(query) {
  const text=normalized(query); let chosen='Motor Skill Development',high=0;
  for(const [strand,keywords] of Object.entries(PE_STRAND_KEYWORDS)){
    const value=keywords.reduce((sum,keyword)=>sum+(text.includes(normalized(keyword))?Math.max(1,keyword.split(' ').length):0),0);
    if(value>high){chosen=strand;high=value;}
  }
  return chosen;
}
function resolvePe(bank,query) {
  const number=PE_STRAND_NUMBER[peStrand(query)]??'1';
  const parent=bank.find((entry)=>entry.isParent&&entry.code.split('.')[1]===number);
  return best(bank.filter((entry)=>entry.parentCode===parent?.code),query)??parent;
}
function resolveHealth(bank,query) {
  return best(bank,query)??bank.find((entry)=>entry.isParent);
}

export function classifiedVirginiaStandards(lesson, subject, explicitTarget='') {
  const subjectKey=subject==='Health'?'Health':'PE';
  const grades=Array.isArray(lesson?.grade_bands)?lesson.grade_bands:[];
  const query=lessonSearchText(lesson);
  const requested=targetCode(explicitTarget);
  return grades.map((grade)=>{
    const bank=VA_SOL_BANKS[subjectKey]?.[String(grade)]??[];
    if(!bank.length){
      const existing=Array.isArray(lesson?.standards)?lesson.standards.find((item)=>Number(item?.grade)===Number(grade)):null;
      return existing??{grade,code:'Virginia SOL',text:'Verify this grade against the official Virginia Standards of Learning.'};
    }
    const exact=requested?.startsWith(String(grade)+'.')?bank.find((entry)=>entry.code.toLowerCase()===requested):null;
    const selected=exact??(subjectKey==='Health'?resolveHealth(bank,query):resolvePe(bank,query));
    return {grade,code:selected.code,text:selected.text};
  });
}
export function classifiedPeStandards(lesson, explicitTarget='') {
  return classifiedVirginiaStandards(lesson,'PE',explicitTarget);
}
